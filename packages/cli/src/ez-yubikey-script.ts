/**
 * The yubikit script that `ykman script --force` runs for `hemlig pki ez` (MIT, written for this project). It is
 * embedded as a string so no `.py` asset has to be shipped; each run writes it to a private temp directory and checks
 * its SHA-256 before executing it.
 *
 * Protocol: one JSON request line on stdin, one `HEMLIG-EZ-RESULT {json}` line on stdout, `HEMLIG-EZ-NOTICE touch <id>`
 * lines on stderr. The script implements a fixed allowlist of operations, every one addressing exactly the slot named
 * in the request. There is no reset, delete, move or attest operation and no operation that takes a second slot.
 * Secrets (PIN, management key, PKCS#8) arrive only on stdin.
 */
